import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const html=readFileSync('dist/index.html','utf8');
assert.match(html,/<progress id="valhalla-progress-bar"/);
const nodes=new Map();
const get=id=>{if(!nodes.has(id))nodes.set(id,{textContent:'',hidden:false,disabled:false,value:0,max:1,setAttribute(){},addEventListener(){}});return nodes.get(id);};
const context={document:{getElementById:get,addEventListener(){}}};context.window=context;
vm.createContext(context);
vm.runInContext(readFileSync('dist/app.js','utf8').replace(/\ninit\(\);\s*$/,''),context);
const state=vm.runInContext('state',context);
const pending=[];
context.routeFetch=()=>new Promise(resolve=>pending.push(resolve));
context.SurviveValhalla={convertRoutes:()=>[]};
vm.runInContext(`
  providerPreflight=async()=>{};
  providerFetch=routeFetch;
  appJson=async response=>({provider_attempted:true,received_at:'2026-09-29T00:00:00Z',response:{},...(response.ok?{}:{error:'Route unavailable'})});
  cancelMapPick=()=>{};renderMapPickControls=()=>{};workflowPhase=()=>{};
  beginWorking=()=>()=>{};providerCounts=()=>{};log=()=>{};notice=()=>{};updateNextAction=()=>{};
`,context);
state.providerStatus={valhalla_ready:true,local_valhalla_ready:true};
const requests=Array.from({length:3},(_,index)=>({index,request_kind:index?'gate_pair':'baseline',round_id:'test-'+index,params:{},maximum_candidates:1,status:'prepared_not_authorized_or_sent'}));
const batch={requests,maximum_requests:3,start_gate_count:1,destination_gate_count:1,status:'prepared_not_authorized_or_sent'};
const draft={round:1,here:{status:'shotgun_batch_prepared_not_authorized_or_sent'},shotgun:{batch}};state.draft=draft;
const run=vm.runInContext('sendShotgun',context)(draft);
for(let i=0;i<10&&!pending.length;i++)await Promise.resolve();
assert.equal(pending.length,1,'first route request waits for a response');
assert.match(get('valhalla-progress-summary').textContent,/0 of 3 requests finished/);
assert.match(get('send-here').textContent,/Searching routes: 0 of 3 finished/);
assert.equal(get('valhalla-progress-bar').value,0);
pending.shift()({ok:true,status:200});
for(let i=0;i<10&&!pending.length;i++)await Promise.resolve();
assert.match(get('valhalla-progress-summary').textContent,/1 of 3 requests finished · 1 successful/);
assert.equal(get('valhalla-progress-bar').value,1);
pending.shift()({ok:false,status:502});
for(let i=0;i<10&&!pending.length;i++)await Promise.resolve();
assert.match(get('valhalla-progress-summary').textContent,/2 of 3 requests finished · 1 successful · 1 confirmed failed/);
assert.equal(get('valhalla-progress-bar').value,2);
pending.shift()({ok:true,status:200});
await run;
assert.match(get('valhalla-progress-summary').textContent,/3 of 3 requests finished · 2 successful · 1 confirmed failed · 0 remaining/);
assert.equal(get('valhalla-progress-bar').value,3);
assert.equal(get('send-here').textContent,'Valhalla search complete');
assert.equal(batch.status,'completed');
assert.equal(state.providerCalls.Valhalla,3);
const unknownBatch={...batch,requests:requests.map(request=>({...request,status:'prepared_not_authorized_or_sent'})),status:'prepared_not_authorized_or_sent'};
const unknownDraft={round:2,here:{status:'shotgun_batch_prepared_not_authorized_or_sent'},shotgun:{batch:unknownBatch}};state.draft=unknownDraft;
context.routeFetch=async()=>{throw Error('Connection lost');};vm.runInContext('providerFetch=routeFetch',context);
await vm.runInContext('sendShotgun',context)(unknownDraft);
assert.equal(unknownBatch.status,'stopped_unknown');
assert.match(get('valhalla-progress-summary').textContent,/0 of 3 requests finished · 0 successful · 0 confirmed failed · 1 outcome unknown · 2 not completed/);
assert.equal(get('valhalla-progress-bar').value,0,'an unknown outcome must not be counted as finished');
assert.equal(get('send-here').textContent,'Valhalla search stopped');
console.log('Passed batch progress through success, confirmed failure, completion, and an unknown outcome. External provider calls: 0.');
