import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const html=readFileSync('dist/index.html','utf8');
assert.match(html,/id="red-cutoff"[^>]*value="200"/);
assert.match(html,/id="color-upper" type="range"[^>]*max="1000"/);
assert.match(html,/id="color-upper-value">\$500 PPSQFT/);
assert.match(html,/data-color-lower/);
assert.match(html,/data-color-upper/);

const elements=new Map();
const get=id=>{if(!elements.has(id))elements.set(id,{value:id==='red-cutoff'?'200':id==='color-upper'?'500':'',textContent:'',disabled:false,setAttribute(){},addEventListener(){}});return elements.get(id);};
const ui={document:{getElementById:get,querySelectorAll(){return[];}},console};
ui.window=ui;
vm.createContext(ui);
vm.runInContext(readFileSync('dist/app.js','utf8').replace(/\ninit\(\);\s*$/,''),ui);
vm.runInContext('drawMap=()=>{globalThis.drawCount=(globalThis.drawCount||0)+1};log=()=>{};notice=()=>{};',ui);
const app=ui.SurviveDrive,state=app.getState();
state.poolScreening.results=[{route_id:'one',rank:1}];state.routes=[{}];vm.runInContext('renderCells=()=>{}',ui);
const originalRanking=JSON.stringify(state.poolScreening.results),originalCalls=JSON.stringify(state.providerCalls);
assert.equal(state.redThresholdPpsqft,200);
assert.equal(state.colorUpperPpsqft,500);
assert.equal(app.color(200),'#f16b2f');
for(const value of [0,50,100,199.99])assert.equal(app.color(value),'#f16b2f','the former red range uses the reddish-orange endpoint');
assert.equal(app.color(null),'#8a96a6','unknown evidence remains gray');
assert.equal(app.color(NaN),'#8a96a6');
assert.equal(app.color(200.000001),'#f16b2f','the scale remains continuous at its lower bound');
assert.equal(app.color(500),'#396bd0');
assert.equal(app.color(2200),'#396bd0');
assert.equal(vm.runInContext('confirmColorUpper(600)',ui),true);
assert.equal(ui.drawCount,1);
assert.equal(state.colorUpperPpsqft,600);
assert.equal(app.color(200),'#f16b2f');
assert.equal(app.color(600),'#396bd0');
assert.equal(app.color(900),'#396bd0');
assert.notEqual(app.color(400),'#396bd0');
assert.equal(JSON.stringify(state.poolScreening.results),originalRanking);
assert.equal(JSON.stringify(state.providerCalls),originalCalls);
assert.equal(vm.runInContext('confirmColorUpper(200)',ui),true,'an upper slider value at the lower bound is nudged to a valid color range');
assert.equal(state.colorUpperPpsqft,201);
assert.equal(ui.drawCount,2);
assert.equal(vm.runInContext('confirmColorUpper(20001)',ui),false);
assert.equal(state.colorUpperPpsqft,201);
assert.equal(app.buildSessionExport().settings.color_upper_ppsqft,201);
vm.runInContext('restoreColorScale({color_upper_ppsqft:450,color_upper_customized:true})',ui);
assert.equal(state.colorUpperPpsqft,450);
assert.equal(app.color(450),'#396bd0');
vm.runInContext('restoreColorScale({})',ui);
assert.equal(state.colorUpperPpsqft,500,'sessions without an upper setting use the new default');
vm.runInContext('restoreColorScale({color_upper_ppsqft:2200,color_upper_customized:false})',ui);
assert.equal(state.colorUpperPpsqft,500,'an old uncustomized upper bound adopts the new default');
vm.runInContext('restoreColorScale({color_upper_ppsqft:2200,color_upper_customized:true})',ui);
assert.equal(state.colorUpperPpsqft,2200,'a user-customized upper bound is preserved');
assert.equal(vm.runInContext('colorUpperFromSlider(0)',ui),2);
assert.equal(vm.runInContext('colorUpperFromSlider(1000)',ui),20000);
assert.equal(vm.runInContext('colorUpperSliderPosition(20000)',ui),1000);
state.redThresholdPpsqft=250;
vm.runInContext('restoreColorScale({})',ui);
assert.equal(state.colorUpperPpsqft,550,'the default color span follows a saved lower bound');
console.log('Passed $200–$500 defaults, color-scale validation, saved settings, and no-ranking-change checks. Provider calls: 0.');
