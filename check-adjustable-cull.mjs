import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const ui={};ui.window=ui;vm.createContext(ui);
vm.runInContext(readFileSync('dist/pool-screening.js','utf8'),ui);
const ids=Array.from({length:8},(_,index)=>`route-${index+1}`);
const ranked=ids.map((route_id,index)=>({route_id,rank:index+1,coverage_pct:50}));
const initial=ui.SurvivePool.screenRoundZeroWithQuota(ranked,ids);
assert.equal(initial.cull_fraction,0.35);
assert.equal(initial.quota,5);
assert.deepEqual(Array.from(initial.disabled_route_ids),ids.slice(5));
const lowCoverage=ranked.map((row,index)=>({...row,coverage_pct:index<6?10:50}));
const protectedFirst=ui.SurvivePool.screenRoundZeroWithQuota(lowCoverage,ids,0.35);
assert.equal(protectedFirst.enabled_route_ids.length,6,'all six low-coverage routes survive even above the quota of five');
assert.deepEqual([1,2,3].map(round=>ui.SurvivePool.routeQuotaForCullRound(8,round,[0.35,0.5,0.25])),[5,2,1]);

const appSource=readFileSync('dist/app.js','utf8');
const start=appSource.indexOf('function applyCullSelection(plan,roundLabel,advance=true)');
const end=appSource.indexOf('function poolAttemptedCellIds()',start);
assert.ok(start>=0&&end>start);
const screen={results:ranked.map((row,index)=>({...row,rank:index===7?1:index+2})),enabled_route_ids:ids.slice(0,5),cull_round:1,cull_fractions:[0.35],next_cull_percent:50,history:[],generation:1};
const client={state:{routes:ids.map(id=>({id})),poolScreening:screen},window:{SurvivePool:ui.SurvivePool},enabledPoolRouteIds:()=>screen.enabled_route_ids};
vm.createContext(client);vm.runInContext(appSource.slice(start,end)+';globalThis.apply=applyCullSelection;',client);
let result=client.apply(null,1);
assert.equal(result.quota,2);
assert.ok(result.enabled_route_ids.includes('route-8'),'a previously excluded route can be promoted');
assert.equal(screen.cull_fractions[1],0.5);
assert.equal(screen.history.at(-1).cull_fraction,0.5);
screen.next_cull_percent=25;
result=client.apply(null,2);
assert.equal(result.quota,1);
assert.equal(screen.cull_fractions[2],0.25);
screen.next_cull_percent=75;
client.apply(null,'rerank',false);
assert.deepEqual(Array.from(screen.cull_fractions),[0.35,0.5,0.25],'reranking preserves completed cutoff percentages');
assert.equal(screen.cull_round,3);
const restoreStart=appSource.indexOf('function restoreSavedRoundZero('),restoreEnd=appSource.indexOf('function loadSessionData(',restoreStart);
assert.ok(restoreStart>=0&&restoreEnd>restoreStart);
const restore={};vm.createContext(restore);vm.runInContext(appSource.slice(restoreStart,restoreEnd)+';globalThis.roundZero=restoreSavedRoundZero;globalThis.fractions=restoreCullFractions;',restore);
const legacyRoundZero={enabled_route_ids:ids.slice(0,5),disabled_route_ids:ids.slice(5),protected_route_ids:[],unprotected_route_ids:ids,considered_route_ids:ids,known_coverage:ranked.map(row=>({route_id:row.route_id,coverage_pct:row.coverage_pct})),fraction:3/8};
assert.equal(restore.roundZero(legacyRoundZero,new Set(ids),ids).cull_fraction,3/8,'an older saved Round 0 keeps its applied percentage');
assert.deepEqual(Array.from(restore.fractions({cull_round:2,round_zero:legacyRoundZero})),[3/8,3/8],'legacy rounds keep their original cutoff instead of changing on import');
assert.match(readFileSync('dist/index.html','utf8'),/id="pool-ranking-cull-percent"[^>]+value="35"/);
assert.match(appSource,/cull_fractions:screen\.cull_fractions\?\?\[\]/,'saved sessions record the cutoff history');
console.log('Adjustable 35% cull, rounding, protection, promotion, and historical percentages passed offline.');
